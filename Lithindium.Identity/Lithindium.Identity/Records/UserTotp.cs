using System;
using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;

// ReSharper disable once CheckNamespace
namespace Lithindium.Identity {

    /// <summary>
    /// Represents an immutable snapshot of a TOTP authenticator associated with a user.
    /// </summary>
    public readonly record struct UserTotp {

        /// <summary>
        /// Gets the universally unique identifier of the authenticator.
        /// </summary>
        public required Guid Uuid { get; init; }

        /// <summary>
        /// Gets the name of the authenticator, or <see langword="null"/> if no name is configured.
        /// </summary>
        public required string? Name { get; init; }

        /// <summary>
        /// Gets the cryptographically protected shared secret of the authenticator.
        /// </summary>
        public required ImmutableArray<byte> Secret { get; init; }

        /// <summary>
        /// Gets the hashing algorithm used by the authenticator.
        /// </summary>
        public required UserTotpAlgorithm Algorithm { get; init; }

        /// <summary>
        /// Gets the number of digits in authentication codes generated by the authenticator.
        /// </summary>
        public required byte Digits { get; init; }

        /// <summary>
        /// Gets the validity period of each authentication code, expressed in seconds.
        /// </summary>
        public required byte Period { get; init; }

        /// <summary>
        /// Gets the most recently accepted authentication time step,
        /// or <see langword="null"/> if no authentication code has been accepted.
        /// </summary>
        /// <remarks>
        /// Used to prevent the replay of previously accepted authentication codes.
        /// </remarks>
        public required ulong? LastStep { get; init; }

        /// <summary>
        /// Constructs a new <see cref="UserTotp"/>
        /// with the specified parameters.
        /// </summary>
        [SetsRequiredMembers]
        public UserTotp(Guid uuid, string? name, ImmutableArray<byte> secret, UserTotpAlgorithm algorithm, byte digits, byte period, ulong? lastStep) {
            Uuid = uuid;
            Name = name;
            Secret = secret;
            Algorithm = algorithm;
            Digits = digits;
            Period = period;
            LastStep = lastStep;
        }

        /// <summary>
        /// Constructs a new <see cref="UserTotp"/>.
        /// </summary>
        public UserTotp() {
            // ...
        }

    }

}
